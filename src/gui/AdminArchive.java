    private void refreshArchiveTable() {
        DefaultTableModel model = (DefaultTableModel) tblArchivedDrivers.getModel();
        model.setRowCount(0);
        try {
            for (Archive driver : archiveService.getArchivedDrivers()) {
                model.addRow(new Object[] {
                    driver.getDriverID(), driver.getDriverName(),
                    driver.getDriverPlateNo(), Boolean.FALSE
                });
            }
        } catch (IllegalStateException ex) {
            javax.swing.JOptionPane.showMessageDialog(this, ex.getMessage(),
                    "Archive Loading Error", javax.swing.JOptionPane.ERROR_MESSAGE);
        }
    }


    private void btnRestoreDriverActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnRestoreDriverActionPerformed
        if (tblArchivedDrivers.isEditing()) {
            tblArchivedDrivers.getCellEditor().stopCellEditing();
        }
        DefaultTableModel model = (DefaultTableModel) tblArchivedDrivers.getModel();
        java.util.List<String> selectedIDs = new java.util.ArrayList<>();

        for (int row = 0; row < model.getRowCount(); row++) {
            if (Boolean.TRUE.equals(model.getValueAt(row, 3))) {
                selectedIDs.add(String.valueOf(model.getValueAt(row, 0)));
            }
        }

        if (selectedIDs.isEmpty()) {
            javax.swing.JOptionPane.showMessageDialog(this,
                    "Select at least one driver using the Select checkbox.",
                    "No Drivers Selected", javax.swing.JOptionPane.INFORMATION_MESSAGE);
            return;
        }

        int restoredCount = 0;
        try {
            for (String id : selectedIDs) {
                if (archiveService.restoreDriver(id)) restoredCount++;
            }
            refreshArchiveTable();
            javax.swing.JOptionPane.showMessageDialog(this,
                    restoredCount + " driver(s) restored successfully.",
                    "Restore Complete", javax.swing.JOptionPane.INFORMATION_MESSAGE);
        } catch (IllegalStateException ex) {
            javax.swing.JOptionPane.showMessageDialog(this, ex.getMessage(),
                    "Restore Error", javax.swing.JOptionPane.ERROR_MESSAGE);
        }
    }//GEN-LAST:event_btnRestoreDriverActionPerformed


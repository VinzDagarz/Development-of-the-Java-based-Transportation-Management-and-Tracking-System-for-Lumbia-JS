    private void btnLoginActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnLoginActionPerformed
        String name = txtName.getText().trim();
        String secret = new String(txtSecret.getPassword());
        String type = String.valueOf(UserType.getSelectedItem());

        if (name.isEmpty()) {
            JOptionPane.showMessageDialog(this, "Please enter your name.", "Login", JOptionPane.WARNING_MESSAGE);
            txtName.requestFocus();
            return;
        }

        Login login = new Login(name, type, secret);

        if ("Admin".equalsIgnoreCase(type)) {
            if (loginService.isAdmin(login)) {
                new AdministratorUser().setVisible(true);
                dispose();
            } else {
                JOptionPane.showMessageDialog(this,
                        "Invalid administrator name or secret password.",
                        "Login Failed", JOptionPane.ERROR_MESSAGE);
            }
        } else if ("Driver".equalsIgnoreCase(type)) {
            Driver driver = loginService.authenticateDriver(login);
            if (driver != null) {
                new DriverUser(driver).setVisible(true);
                dispose();
            } else {
                JOptionPane.showMessageDialog(this,
                        "Driver account not found or archived. The administrator must create the driver first.",
                        "Login Failed", JOptionPane.ERROR_MESSAGE);
            }
        } else if ("Passenger".equalsIgnoreCase(type)) {
            if (!service.DBConnection.isAvailable()) {
                JOptionPane.showMessageDialog(this,
                        "Passenger login requires an online XAMPP/MySQL database.",
                        "Database Offline", JOptionPane.WARNING_MESSAGE);
            } else if (loginService.isPassenger(login)) {
                new PassengerUser(name).setVisible(true);
                dispose();
            }
        }
    }//GEN-LAST:event_btnLoginActionPerformed

